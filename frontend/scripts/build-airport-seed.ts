// Builds the airport seed migration from the OurAirports airports.csv (public domain).
//
//   pnpm exec tsx scripts/build-airport-seed.ts <airports.csv> <out.sql>
//
// Download the CSV from https://davidmegginson.github.io/ourairports-data/airports.csv into a scratch
// directory (it is data only, never executed). The output is the content of
// supabase/migrations/<ts>_airport_seed.sql: batched `insert ... on conflict (ident) do nothing`.
//
// Kept columns: ident, type, name, latitude_deg, longitude_deg, iso_country, iso_region, municipality,
// scheduled_service, gps_code, iata_code, local_code.
// Included rows: every airport with an IATA code, plus small/medium/large airports that have a 4-letter
// alphabetic ICAO or (US only) a FAA/local code; non-US strips with only a local code are left out to keep
// the seed under ~4 MB (free-text fallback covers them). Excluded: heliports, closed fields, seaplane bases and balloonports
// unless they have an IATA code.
// Derived: icao = gps_code if 4 letters, else ident if 4 letters, else null; faa = local_code (US only);
// iata = iata_code.

import { readFileSync, writeFileSync } from 'node:fs'

const KEEP_TYPES = new Set(['small_airport', 'medium_airport', 'large_airport'])
const FOUR_LETTERS = /^[A-Z]{4}$/
const BATCH = 500

/** Minimal RFC 4180 parser (quoted fields, doubled quotes, newlines inside quotes). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else quoted = false
      } else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      field = ''
      if (row.length > 1 || row[0] !== '') rows.push(row)
      row = []
    } else field += c
  }
  if (field !== '' || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

export type SeedAirport = {
  ident: string
  icao: string | null
  iata: string | null
  faa: string | null
  name: string
  city: string | null
  region: string | null
  country: string
  type: string
  latitude: number | null
  longitude: number | null
  scheduledService: boolean
}

export function toSeedAirport(r: Record<string, string>): SeedAirport | null {
  const iata = r.iata_code?.trim().toUpperCase() || null
  const local = r.local_code?.trim().toUpperCase() || null
  const ident = r.ident.trim().toUpperCase()
  const gps = r.gps_code?.trim().toUpperCase() ?? ''
  const icao = FOUR_LETTERS.test(gps)
    ? gps
    : FOUR_LETTERS.test(ident)
      ? ident
      : null
  const keep =
    iata ||
    (KEEP_TYPES.has(r.type) && (icao || (r.iso_country === 'US' && local)))
  if (!keep || !ident) return null
  const lat = Number.parseFloat(r.latitude_deg)
  const lon = Number.parseFloat(r.longitude_deg)
  return {
    ident,
    icao,
    iata,
    faa: r.iso_country === 'US' ? local : null,
    name: r.name.trim(),
    city: r.municipality.trim() || null,
    region: r.iso_region.trim() || null,
    country: r.iso_country.trim(),
    type: r.type,
    latitude: Number.isFinite(lat) ? Number(lat.toFixed(5)) : null,
    longitude: Number.isFinite(lon) ? Number(lon.toFixed(5)) : null,
    scheduledService: r.scheduled_service === 'yes'
  }
}

const q = (v: string | null) =>
  v === null ? 'null' : `'${v.replace(/'/g, "''")}'`
const n = (v: number | null) => (v === null ? 'null' : String(v))

function valuesRow(a: SeedAirport): string {
  return `(${[
    q(a.ident),
    q(a.icao),
    q(a.iata),
    q(a.faa),
    q(a.name),
    q(a.city),
    q(a.region),
    q(a.country),
    q(a.type),
    n(a.latitude),
    n(a.longitude),
    a.scheduledService ? 'true' : 'false'
  ].join(',')})`
}

function main() {
  const [csvPath, outPath] = process.argv.slice(2)
  if (!csvPath || !outPath) {
    console.error('usage: build-airport-seed.ts <airports.csv> <out.sql>')
    process.exit(1)
  }
  const [header, ...body] = parseCsv(readFileSync(csvPath, 'utf8'))
  const records = body.map((cells) =>
    Object.fromEntries(header.map((h, i) => [h, cells[i] ?? '']))
  )
  const seen = new Set<string>()
  const airports: SeedAirport[] = []
  for (const r of records) {
    const a = toSeedAirport(r)
    if (a && !seen.has(a.ident)) {
      seen.add(a.ident)
      airports.push(a)
    }
  }
  airports.sort((x, y) => (x.ident < y.ident ? -1 : 1))

  const lines = [
    '-- Airport seed: OurAirports (public domain, https://ourairports.com/data/), generated by',
    '-- frontend/scripts/build-airport-seed.ts. Do not edit by hand: regenerate and replace.',
    `-- ${airports.length} airports. Idempotent: existing idents are left alone (on conflict do nothing).`,
    '',
    'begin;',
    ''
  ]
  for (let i = 0; i < airports.length; i += BATCH) {
    lines.push(
      'insert into public.airport (ident, icao, iata, faa, name, city, region, country, type, latitude, longitude, scheduled_service) values'
    )
    lines.push(
      airports
        .slice(i, i + BATCH)
        .map(valuesRow)
        .join(',\n')
    )
    lines.push('on conflict (ident) do nothing;', '')
  }
  lines.push('commit;', '')
  const sql = lines.join('\n')
  writeFileSync(outPath, sql)

  const count = (f: (a: SeedAirport) => boolean) => airports.filter(f).length
  console.log(`csv rows: ${records.length}`)
  console.log(`seeded airports: ${airports.length}`)
  console.log(`  with iata: ${count((a) => !!a.iata)}`)
  console.log(`  with icao: ${count((a) => !!a.icao)}`)
  console.log(`  with faa:  ${count((a) => !!a.faa)}`)
  console.log(`  US:        ${count((a) => a.country === 'US')}`)
  console.log(
    `sql size: ${(Buffer.byteLength(sql) / 1024 / 1024).toFixed(2)} MB`
  )
}

if (process.argv[1]?.endsWith('build-airport-seed.ts')) main()
